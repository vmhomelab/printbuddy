function deviceLocale(): string {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale ?? 'en';
  } catch {
    return 'en';
  }
}

export const locale = deviceLocale();
export const t: Strings = locale.toLowerCase().startsWith('de') ? de : en;
