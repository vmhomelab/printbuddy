class TestVirtualPrinterHostEndpoint:
    @pytest.mark.asyncio
    @pytest.mark.integration
    async def test_version_requires_valid_key(self, async_client: AsyncClient, no_sync):
        vp = await _create(async_client, enabled=True)
        base = vp["host_path"]

        assert (await async_client.get(f"{base}/api/version")).status_code == 401
        assert (await async_client.get(f"{base}/api/version", headers={"X-Api-Key": "wrong"})).status_code == 401
        assert (
            await async_client.get("/api/v1/vp-host/9999/api/version", headers={"X-Api-Key": "x"})
        ).status_code == 401

        response = await async_client.get(f"{base}/api/version", headers={"X-Api-Key": vp["api_key"]})
        assert response.status_code == 200
        # OrcaSlicer/PrusaSlicer reject hosts whose text doesn't start with "OctoPrint".
        assert response.json()["text"].startswith("OctoPrint")

        response = await async_client.get(f"{base}/server/info?apikey={vp['api_key']}")
        assert response.status_code == 200
        assert response.json()["result"]["klippy_state"] == "ready"

    @pytest.mark.asyncio
    @pytest.mark.integration
    async def test_disabled_vp_refuses(self, async_client: AsyncClient, no_sync):
        vp = await _create(async_client, enabled=False)
        response = await async_client.get(f"{vp['host_path']}/api/version", headers={"X-Api-Key": vp["api_key"]})
        assert response.status_code == 409

    @pytest.mark.asyncio
    @pytest.mark.integration
    @pytest.mark.parametrize("upload_path", ["api/files/local", "server/files/upload"])
    async def test_upload_hands_file_to_instance(
        self, async_client: AsyncClient, no_sync, tmp_path: Path, upload_path: str
    ):
        vp = await _create(async_client, enabled=True)
        received: list[Path] = []

        async def on_file_received(path: Path, source_ip: str) -> None:
            received.append(path)
            assert path.read_text() == GCODE

        instance = MagicMock(is_http_host=True, upload_dir=tmp_path)
        instance.on_file_received = AsyncMock(side_effect=on_file_received)

        with patch("backend.app.services.virtual_printer.virtual_printer_manager.get_instance", return_value=instance):
            response = await async_client.post(
                f"{vp['host_path']}/{upload_path}",
                headers={"X-Api-Key": vp["api_key"]},
                files={"file": ("../../evil/U1 Benchy.gcode", GCODE.encode(), "application/octet-stream")},
                data={"print": "true"},
            )
            assert response.status_code == 201, response.text
            assert [p.name for p in received] == ["U1 Benchy.gcode"]
            assert received[0].parent == tmp_path

            response = await async_client.post(
                f"{vp['host_path']}/{upload_path}",
                headers={"X-Api-Key": vp["api_key"]},
                files={"file": ("payload.sh", b"echo hi", "application/octet-stream")},
            )
            assert response.status_code == 415

            response = await async_client.post(
                f"{vp['host_path']}/{upload_path}",
                headers={"X-Api-Key": "wrong"},
                files={"file": ("x.gcode", b"G28", "application/octet-stream")},
            )
            assert response.status_code == 401
        assert instance.on_file_received.await_count == 1


@pytest.mark.asyncio
@pytest.mark.integration
async def test_gcode_upload_is_archived_and_queued_for_target(
    test_engine,
    db_session: AsyncSession,
    printer_factory,
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
):
    """Raw G-code from a Moonraker-compatible VP lands in the archive with its
    header metadata and is queued for the configured non-Bambu printer."""
    monkeypatch.setattr(settings, "base_dir", tmp_path)
    monkeypatch.setattr(settings, "archive_dir", tmp_path / "archives")
    settings.archive_dir.mkdir(parents=True, exist_ok=True)

    target = await printer_factory(name="U1", provider="klipper")
    session_factory = async_sessionmaker(test_engine, class_=AsyncSession, expire_on_commit=False)
    instance = VirtualPrinterInstance(
        vp_id=7,
        name="U1 VP",
        mode="print_queue",
        model="BL-P001",
        access_code="",
        serial_suffix="391800007",
        protocol="moonraker",
        target_printer_id=target.id,
        auto_dispatch=True,
        base_dir=tmp_path,
        session_factory=session_factory,
    )
    assert instance.is_running

    upload = instance.upload_dir / "Benchy.gcode"
    upload.write_text(GCODE)
    await instance.on_file_received(upload, "192.0.2.20")

    archive = (await db_session.execute(select(PrintArchive))).scalar_one()
    assert archive.filename == "Benchy.gcode"
    assert archive.print_time_seconds == 3723
    assert archive.filament_used_grams == 12.34
    assert archive.filament_type == "PLA, PETG"
    assert archive.sliced_for_model == "Snapmaker U1"

    item = (await db_session.execute(select(PrintQueueItem))).scalar_one()
    assert item.printer_id == target.id
    assert item.target_model is None
    assert item.plate_id is None
    assert item.manual_start is False
    assert not upload.exists()


