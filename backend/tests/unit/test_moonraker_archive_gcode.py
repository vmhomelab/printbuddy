"""Copy the G-code of Klipper prints started outside Printbuddy into the archive.

Prints started from Fluidd, Mainsail or a slicer only got a fileless archive
and could not be reprinted. ``_attach_moonraker_gcode`` streams the file from
Moonraker into the archive's folder and sets ``file_path``.
"""

import httpx
import pytest
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from backend.app.services.printer_providers.moonraker import MoonrakerPrinterClient

GCODE = b"; generated by OrcaSlicer\nG28\n" + b"G1 X10 Y10 E1\n" * 2000


def _client_serving(monkeypatch, files: dict[str, bytes], *, send_length: bool = True):
    requests: list[str] = []

    def handler(request: httpx.Request) -> httpx.Response:
        requests.append(request.url.raw_path.decode())
        prefix = "/server/files/gcodes/"
        name = request.url.path.removeprefix(prefix)
        if name not in files:
            return httpx.Response(404, json={"error": "not found"})
        body = files[name]
        if send_length:
            return httpx.Response(200, content=body)

        def stream():
            yield body

        return httpx.Response(200, content=stream())

    client = MoonrakerPrinterClient("http://klipper.local:7125")
    http = httpx.Client(transport=httpx.MockTransport(handler))
    monkeypatch.setattr(client, "_http_client", lambda: http)
    return client, requests


def test_download_file_to_streams_into_the_file(tmp_path, monkeypatch):
    client, requests = _client_serving(monkeypatch, {"parts/benchy v2.gcode": GCODE})
    dest = tmp_path / "out" / "benchy v2.gcode"

    assert client.download_file_to("parts/benchy v2.gcode", dest) == len(GCODE)
    assert dest.read_bytes() == GCODE
    assert requests == ["/server/files/gcodes/parts/benchy%20v2.gcode"]


def test_download_file_to_returns_none_for_a_missing_file(tmp_path, monkeypatch):
    client, _ = _client_serving(monkeypatch, {})
    dest = tmp_path / "missing.gcode"

    assert client.download_file_to("missing.gcode", dest) is None
    assert not dest.exists()


@pytest.mark.parametrize("send_length", [True, False])
def test_download_file_to_stops_over_the_size_limit(tmp_path, monkeypatch, send_length):
    client, _ = _client_serving(monkeypatch, {"big.gcode": GCODE}, send_length=send_length)
    dest = tmp_path / "big.gcode"

    assert client.download_file_to("big.gcode", dest, max_bytes=len(GCODE) - 1) is None
    assert not dest.exists()


