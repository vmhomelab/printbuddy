class _FakeClient:
    def __init__(self, body: bytes | None):
        self.body = body
        self.calls: list[tuple[str, int | None]] = []

    def download_file_to(self, remote_path, dest, *, max_bytes=None):
        self.calls.append((remote_path, max_bytes))
        if self.body is None or (max_bytes is not None and len(self.body) > max_bytes):
            return None
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(self.body)
        return len(self.body)


@pytest.fixture
def archive_env(tmp_path, monkeypatch, test_engine):
    import backend.app.main as main
    from backend.app.services import archive as archive_module

    monkeypatch.setattr(archive_module.settings, "base_dir", tmp_path)
    monkeypatch.setattr(archive_module.settings, "archive_dir", tmp_path / "archive")
    monkeypatch.setattr(main.app_settings, "base_dir", tmp_path)
    session_maker = async_sessionmaker(test_engine, class_=AsyncSession, expire_on_commit=False)
    monkeypatch.setattr(main, "async_session", session_maker)
    return main, session_maker, tmp_path


async def _fileless_archive(session_maker, **overrides):
    from backend.app.models.archive import PrintArchive

    async with session_maker() as db:
        archive = PrintArchive(
            printer_id=None,
            filename="parts/benchy.gcode",
            file_path="",
            file_size=0,
            print_name="benchy",
            status="printing",
            extra_data={"no_3mf_available": True},
            **overrides,
        )
        db.add(archive)
        await db.commit()
        await db.refresh(archive)
        return archive.id


async def _load(session_maker, archive_id):
    from backend.app.models.archive import PrintArchive

    async with session_maker() as db:
        return await db.get(PrintArchive, archive_id)


@pytest.mark.asyncio
async def test_attach_copies_the_gcode_into_the_fileless_archive(archive_env, monkeypatch):
    import logging

    main, session_maker, tmp_path = archive_env
    fake = _FakeClient(GCODE)
    monkeypatch.setattr(main.printer_manager, "get_client", lambda printer_id: fake)
    archive_id = await _fileless_archive(session_maker)

    assert await main._attach_moonraker_gcode(1, archive_id, "parts/benchy.gcode", logging.getLogger("t")) is True

    archive = await _load(session_maker, archive_id)
    assert archive.file_path == f"archive/_fileless/{archive_id}/benchy.gcode"
    assert archive.file_size == len(GCODE)
    assert archive.content_hash
    assert archive.extra_data["gcode_source"] == "moonraker"
    assert archive.extra_data["no_3mf_available"] is True
    assert (tmp_path / archive.file_path).read_bytes() == GCODE
    # Default limit: 200 MB
    assert fake.calls == [("parts/benchy.gcode", 200 * 1024 * 1024)]


